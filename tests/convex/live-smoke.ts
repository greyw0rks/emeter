import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { createPublicClient, http } from "viem";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { EmeterClient, EmeterGatewayError } from "@emeter/sdk";

const root = fileURLToPath(new URL("../../", import.meta.url));
const hosted = JSON.parse(await readFile(join(root, "deployments/convex.json"), "utf8"));
const engine = JSON.parse(await readFile(join(root, "deployments/xlayer-196-engine.json"), "utf8"));
const target = process.argv.includes("--production") ? "production" : "development";
const url = hosted[target].httpUrl as string;
const account = privateKeyToAccount(generatePrivateKey());
const sdk = new EmeterClient({ gatewayUrl: url, rpcUrl: "https://rpc.xlayer.tech", vault: engine.contracts.vault, registry: engine.contracts.registry });
const checks: { name: string; passed: true }[] = [];
const check = (name: string) => checks.push({ name, passed: true });
const network = await sdk.getNetwork();
assert.equal(network.chainId, 196); assert.equal(network.networkMode, "mainnet");
assert(network.anchor);
const block = await createPublicClient({ transport: http("https://rpc.xlayer.tech") }).getBlock({ blockNumber: BigInt(network.anchor.blockNumber) });
assert.equal(block.hash.toLowerCase(), network.anchor.blockHash.toLowerCase());
check("Hosted protocol pins the existing deployment and matching block hash");
await assert.rejects(sdk.getAccount(), (error: unknown) => error instanceof EmeterGatewayError && error.status === 401);
check("Anonymous account reads are refused");
await sdk.authenticate(account);
const profile = await sdk.getAccount() as { wallet: string; availableBaseUnits: string; sessions: unknown[] };
assert.equal(profile.wallet, account.address.toLowerCase()); assert.equal(profile.availableBaseUnits, "0");
check("Hosted origin-bound wallet challenge and account lookup work");
await assert.rejects(sdk.getRequest("0x" + "f".repeat(64) as `0x${string}`), (error: unknown) => error instanceof EmeterGatewayError && error.status === 404);
check("Unknown receipts do not expose another wallet's records");
const preflight = await fetch(url + "/api/auth/challenge", { method: "OPTIONS", headers: { origin: "http://127.0.0.1:3100", "access-control-request-headers": "authorization,content-type" } });
assert.equal(preflight.status, 204); assert.equal(preflight.headers.get("access-control-allow-origin"), "http://127.0.0.1:3100");
const denied = await fetch(url + "/api/account", { headers: { origin: "https://unconfigured.example" } });
assert.equal(denied.status, 403);
check("Hosted CORS preflight is scoped to configured origins");
await sdk.logout();
await assert.rejects(sdk.getAccount(), (error: unknown) => error instanceof EmeterGatewayError && error.status === 401);
check("Hosted credential revocation is enforced");
const result = { kind: "convex-hosted-read-only-smoke", target, url, chainId: 196, checks, signingClassification: "temporary builder-controlled wallet challenge only",
  mainnetBroadcastPerformed: false, upstreamAiCalls: 0, completedAt: new Date().toISOString() };
await writeFile(join(root, "docs/evidence/convex-" + target + "-smoke.json"), JSON.stringify(result, null, 2) + "\n");
console.log(JSON.stringify({ target, passed: true, checks: checks.length, url }));
