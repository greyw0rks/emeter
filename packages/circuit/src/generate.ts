import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { policyArtifact } from "./index.js";

const artifact = policyArtifact();
const artifactsDir = new URL("../artifacts/", import.meta.url);
const contractsDir = new URL("../../contracts/src/generated/", import.meta.url);
await mkdir(artifactsDir, { recursive: true });
await mkdir(contractsDir, { recursive: true });
await writeFile(new URL("policy-v1.json", artifactsDir), JSON.stringify(artifact, null, 2) + "\n");
await writeFile(new URL("policy-v1.hex", artifactsDir), artifact.netlist + "\n");
await writeFile(new URL("EmeterPolicyV1.sol", contractsDir), `// SPDX-License-Identifier: MIT
// Generated by packages/circuit/src/generate.ts. Regenerate; do not edit.
pragma solidity ^0.8.24;

library EmeterPolicyV1 {
    uint32 internal constant N_IN = 6;
    uint32 internal constant N_OUT = 1;
    uint32 internal constant N_STATE = 0;
    uint32 internal constant GATE_COUNT = ${artifact.gateCount};
    bytes32 internal constant NETLIST_HASH = ${artifact.netlistHash};

    function netlist() internal pure returns (bytes memory) {
        return hex"${artifact.netlist.slice(2)}";
    }
}
`);
console.log(JSON.stringify({ artifact: fileURLToPath(new URL("policy-v1.json", artifactsDir)), gateCount: artifact.gateCount, bytes: (artifact.netlist.length - 2) / 2, netlistHash: artifact.netlistHash, vectors: artifact.truthTable.length }, null, 2));
